/** The API handed to one plugin's `activate` (`staged`: its staged `api.stickers` and `api.themes`). */
export function createPluginApi(
  plugin: InstalledPlugin,
  { stickers, themes }: PluginStaged,
): PluginApi {
  return strictApi<PluginApi>(
    {
      apiVersion: PLUGIN_API_VERSION,
      plugin: {
        id: plugin.manifest.id,
        manifest: plugin.manifest,
        readAsset: (path) => pluginStorage.readAsset(plugin, path),
        readText: async (path) =>
          new TextDecoder().decode(await pluginStorage.readAsset(plugin, path)),
      },
      core: { defineModule, definePoint, createId },
      canvas: {
        ElementKind,
        BoxKind,
        TextBoxKind,
        LineKind,
        ELEMENT_DEFAULTS,
        createElementBase,
        defineService,
        selectAndEdit,
        asUndoStep,
        buildElement,
        summarizeElement,
        stringArg,
        optionalString,
        optionalNumber,
        optionalBoolean,
        optionalChoice,
        stringList,
        optionalRecord,
        recordList,
        clamp,
        roundPoint,
        fitInView,
        elementBounds,
        rotatePoint,
        scaleRect,
        scaleLength,
        toUnrotated,
        gradientCss,
        gradientHandles,
        transformFromHandles,
        pastThreshold,
        DRAW_THRESHOLD_PX,
        MOVE_THRESHOLD_PX,
        FreehandTool,
        smoothPoints,
        measureTextBlock,
        textFont,
        fontFamilyList,
      },
      ui: {
        React,
        toast,
        notifyError,
        FloatingPanel,
        PanelDivider,
        ToolButton,
        OptionButton,
        ColorSwatch,
        ColorPalette,
        ColorField,
        ColorPopover,
        chooseImageAsset,
        ImageChooseButton,
        ModeToolbar,
        ModeToolbarItem,
        ElementThumbnail,
        useElementThumbnail,
        AnchorPicker,
        ExtensionIconView,
        useEngine,
        useEngineState,
        useService,
        useEngineElement,
        kit,
      },
      board: {
        canvas: boardCanvas,
        editor: boardEditor,
        mcpTools: boardMcpTools,
        library: boardLibrary,
        erStandards: boardErStandards,
        defineErStandard,
        erConstructs: boardErConstructs,
        defineErConstruct,
        requireBoard,
        palette: { STICKY_COLORS, SHAPE_FILLS, SHAPE_STROKES, LINE_COLORS, INK_COLOR },
      },
      design: {
        canvas: designCanvas,
        editor: designEditor,
        migrations: designMigrations,
        mcpTools: designMcpTools,
        requireDesign,
        tree: DESIGN_TREE,
        pages: DESIGN_PAGES,
        nodes: {
          DesignNodeKind,
          createNodeBase,
          isDesignNode,
          solidPaint,
          imagePaint,
          gradientPaint,
          isGradientPaint,
          drawPaints,
          traceBox,
          NODE_DEFAULTS,
          BoxShapeKind,
          PointsShapeKind,
          NodeDrawTool,
          BoxDrawTool,
          containerAt,
          parentFor,
          layerNameOf,
          pointsInBox,
          pointInPolygon,
          distanceToOutline,
        },
        network: {
          polylineNetwork,
          polygonNetwork,
          rectNetwork,
          ellipseNetwork,
          placeNetwork,
          scaleNetwork,
          networkBounds,
          hitSegment,
          vertexAt,
          insideRegion,
          traceStrokes,
          traceRegions,
          splitSegment,
          connect,
          addVertex,
          moveVertices,
          setTangent,
          removeParts,
          cutSegment,
          bendSegment,
          toggleSmooth,
          toggleRegion,
          networkFaces,
          faceAt,
          VectorEditTool,
          VECTOR_EDIT,
          VECTOR_TOOLS,
        },
        panel: {
          PanelSection,
          PanelIconButton,
          PanelAddButton,
          NumberField,
          NodeNumberField,
          NodeSelectField,
          NodeCheckbox,
          NodeOptionButtons,
          FieldBox,
          HexInput,
          PercentInput,
          PaintField,
          PropertyGrid,
          sharedValue,
        },
        sections: { ofType, allKinds, someNodes, noNodes },
        effects: {
          effectTypes: designEffectTypes,
          defineEffectType,
          setEffectReader,
          localUniforms,
          LOCAL_GLSL,
          LOCAL_UNIFORMS,
          NOISE_GLSL,
          EffectShader,
          FILTER_HEADER,
          SAMPLING_GLSL,
          silhouetteShader,
          underShader,
          atopShader,
          shapeUnderShader,
          ScrubField,
          EffectChoice,
        },
        hooks: {
          useSelectedNodes,
          useEditNodes,
          useMoveNodes,
          useDesignEngine,
          useDesignState,
        },
      },
      stickers,
      themes,
    },
    "api",
  );
}
