/** The API handed to one plugin's `activate`. */
export function createPluginApi(plugin: InstalledPlugin): PluginApi {
  return strictApi<PluginApi>(
    {
      apiVersion: PLUGIN_API_VERSION,
      plugin: {
        id: plugin.manifest.id,
        manifest: plugin.manifest,
        readAsset: (path) => pluginStorage.readAsset(plugin, path),
        readText: async (path) =>
          new TextDecoder().decode(await pluginStorage.readAsset(plugin, path)),
      },
      core: { defineModule, definePoint, createId },
      canvas: {
        ElementKind,
        BoxKind,
        TextBoxKind,
        LineKind,
        ELEMENT_DEFAULTS,
        createElementBase,
        defineService,
        selectAndEdit,
        asUndoStep,
        buildElement,
        summarizeElement,
        stringArg,
        optionalString,
        optionalNumber,
        optionalBoolean,
        optionalChoice,
        stringList,
        optionalRecord,
        recordList,
        clamp,
        roundPoint,
        fitInView,
        pastThreshold,
        DRAW_THRESHOLD_PX,
        MOVE_THRESHOLD_PX,
        FreehandTool,
        smoothPoints,
        measureTextBlock,
        textFont,
        fontFamilyList,
      },
      ui: {
        React,
        toast,
        notifyError,
        FloatingPanel,
        PanelDivider,
        ToolButton,
        OptionButton,
        ColorSwatch,
        ColorPalette,
        ExtensionIconView,
        useEngine,
        useEngineState,
        useService,
        useEngineElement,
      },
      board: {
        canvas: boardCanvas,
        editor: boardEditor,
        agentTools: boardAgentTools,
        library: boardLibrary,
        requireBoard,
        palette: { STICKY_COLORS, SHAPE_FILLS, SHAPE_STROKES, LINE_COLORS, INK_COLOR },
      },
      design: {
        canvas: designCanvas,
        editor: designEditor,
        migrations: designMigrations,
        tree: DESIGN_TREE,
        nodes: {
          DesignNodeKind,
          createNodeBase,
          isDesignNode,
          solidPaint,
          imagePaint,
          drawPaints,
          traceBox,
          NODE_DEFAULTS,
          BoxShapeKind,
          PointsShapeKind,
          NodeDrawTool,
          BoxDrawTool,
          containerAt,
          parentFor,
          layerNameOf,
          pointsInBox,
          pointInPolygon,
          distanceToOutline,
        },
        network: {
          polylineNetwork,
          polygonNetwork,
          rectNetwork,
          ellipseNetwork,
          placeNetwork,
          scaleNetwork,
          networkBounds,
          hitSegment,
          vertexAt,
          insideRegion,
          traceStrokes,
          traceRegions,
          splitSegment,
          connect,
          addVertex,
          moveVertices,
          setTangent,
          removeParts,
          cutSegment,
          bendSegment,
          toggleSmooth,
          VectorEditTool,
          VECTOR_EDIT,
          VECTOR_TOOLS,
        },
        panel: {
          PanelSection,
          PanelIconButton,
          PanelAddButton,
          NumberField,
          NodeNumberField,
          NodeSelectField,
          NodeCheckbox,
          NodeOptionButtons,
          FieldBox,
          HexInput,
          PercentInput,
          PaintField,
          PropertyGrid,
          sharedValue,
        },
        sections: { ofType, allKinds, someNodes, noNodes },
        hooks: {
          useSelectedNodes,
          useEditNodes,
          useMoveNodes,
          useDesignEngine,
          useDesignState,
        },
      },
    },
    "api",
  );
}
