import type { CanvasElement } from "@canvas";

import { isDesignNode } from "../../core";
import { isFrame } from "../../frame";
import type { GeneratedMark, SheetFrame } from "./sheet.types";

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Whether an element is a live design-system element: a frame with a well-formed `sheet`. */
export function isSheet(el: CanvasElement | undefined): el is SheetFrame {
  if (!isFrame(el)) return false;
  const sheet = (el as { sheet?: unknown }).sheet;
  return (
    isRecord(sheet) &&
    typeof sheet.category === "string" &&
    (sheet.group === undefined || typeof sheet.group === "string") &&
    (sheet.template === null || typeof sheet.template === "string") &&
    (sheet.options === null || isRecord(sheet.options)) &&
    (sheet.modeView === "current" || sheet.modeView === "all") &&
    typeof sheet.hash === "string"
  );
}

/** What marks a layer as generated by a sheet, or `null` for the user's own layers. */
export function generatedMark(el: CanvasElement | undefined): GeneratedMark | null {
  if (!el || !isDesignNode(el)) return null;
  const mark = (el as { generated?: unknown }).generated;
  return isRecord(mark) && typeof mark.sheet === "string" && typeof mark.key === "string"
    ? { sheet: mark.sheet, key: mark.key }
    : null;
}
