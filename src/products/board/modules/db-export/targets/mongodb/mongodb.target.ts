import { defineCodeTarget } from "../define-code-target";
import { focusTables } from "../focus-tables";
import type { CodeWarning } from "../warnings.types";
import { writeCollection } from "./write-collection";

/**
 * MongoDB: one `mongosh` script creating each collection with a `$jsonSchema` validator and its
 * indexes (the primary key and unique columns become unique indexes; documents keep their own
 * `_id`). Single mode: the table's collection, in `<table>.mongodb.js`.
 */
export const mongodbTarget = defineCodeTarget({
  id: "mongodb",
  label: "MongoDB",
  profiles: [{ id: "8", label: "MongoDB 8", flags: {} }],
  options: [],
  generate(schema, request) {
    const warnings: CodeWarning[] = [];
    const tables = focusTables(schema, request);
    const header = `// Generated by Cloudy Canvas for ${request.profile.label}. Run it with mongosh.\n`;
    const collections = tables.map((table) => writeCollection(table, schema.enums, warnings));
    const name = request.mode === "single" && tables[0] ? tables[0].name : "schema";
    return {
      files: [
        {
          path: `${name}.mongodb.js`,
          content: [header, ...collections].join("\n"),
          language: "js",
        },
      ],
      warnings,
    };
  },
});
