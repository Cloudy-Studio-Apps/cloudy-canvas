import type { CodeColumn, CodeDefault, CodeEnum, CodeIndex, CodeTable } from "../../model";

/** A column's SQL type, or `null` when the dialect has none (the writer warns and uses `text`). */
export type SqlType = string | null;

/** What differs between the SQL databases the DDL writer targets. */
export interface SqlDialect {
  /** The target's name in warnings, e.g. "PostgreSQL". */
  name: string;
  /** Quotes an identifier when it needs it (reserved word, unusual characters). */
  id(name: string): string;
  columnType(column: CodeColumn, enums: readonly CodeEnum[]): SqlType;
  /** The type an unknown column falls back to. */
  fallbackType: string;
  /** What makes an integer column count up (`GENERATED BY DEFAULT AS IDENTITY`). */
  increment: string;
  /** A `CREATE TYPE` for an enum, or `null` where enums are written inline. */
  enumType(e: CodeEnum): string | null;
  defaultValue(value: CodeDefault, column: CodeColumn): string;
  /** Inline column comment (`COMMENT '…'`), or `null` to write `COMMENT ON` after the table. */
  columnComment(note: string): string | null;
  /** Statements after the table: comments where they aren't inline. */
  comments(table: CodeTable): string[];
  /** Text after the closing parenthesis, e.g. MySQL's table comment. */
  tableSuffix(table: CodeTable): string;
  /** Index methods it takes (`USING`); an index with another method is written without one. */
  indexMethods: ReadonlySet<string>;
  /** `CREATE INDEX …;`. */
  index(table: CodeTable, index: CodeIndex, name: string): string;
}
