import { focusTables } from "../focus-tables";
import { indexName } from "../../code";
import type { CodeSchema, CodeTable } from "../../model";
import type { CodeOutput, CodeRequest } from "../code-target.types";
import { warn } from "../warnings";
import type { CodeWarning } from "../warnings.types";
import type { SqlDialect } from "./sql-dialect.types";
import { foreignKey, writeTable } from "./write-table";

/**
 * The schema as one DDL script: enum types, the tables in foreign key order (their foreign keys
 * inline), their indexes and comments, then the foreign keys that close a cycle. In single mode,
 * the one table (every foreign key inline) and the enum types it uses, in `<table>.sql`.
 */
export function writeDdl(
  schema: CodeSchema,
  dialect: SqlDialect,
  request: CodeRequest,
): CodeOutput {
  const warnings: CodeWarning[] = [];
  const single = request.mode === "single";
  const tables = single ? focusTables(schema, request) : schema.tables;
  const used = new Set(tables.flatMap((table) => table.columns.map((c) => c.enum)));
  const enums = schema.enums.filter((e) => !single || used.has(e.name));
  const deferred = single ? [] : schema.deferred;

  const parts: string[] = [`-- Generated by Cloudy Canvas for ${request.profile.label}\n`];
  const enumTypes = enums.flatMap((e) => dialect.enumType(e) ?? []);
  if (enumTypes.length > 0) parts.push(`${enumTypes.join("\n")}\n`);
  for (const table of tables) {
    const inline = table.outgoing.filter((relation) => !deferred.includes(relation));
    parts.push(writeTable(table, dialect, schema.enums, inline, warnings));
    const after = [...indexes(table, dialect, warnings), ...dialect.comments(table)];
    if (after.length > 0) parts.push(`${after.join("\n")}\n`);
  }
  if (deferred.length > 0) {
    parts.push(
      `${deferred
        .map((relation) => {
          warnings.push(
            warn(
              "fk-cycle",
              { table: relation.from.table, column: relation.from.column },
              { table: relation.from.table, column: relation.from.column },
            ),
          );
          return `ALTER TABLE ${dialect.id(relation.from.table)} ADD ${foreignKey(relation, dialect)};`;
        })
        .join("\n")}\n`,
    );
  }
  if (!single) {
    for (const relation of schema.manyToMany) {
      warnings.push(
        warn(
          "many-to-many",
          { from: relation.from.table, to: relation.to.table },
          { table: relation.from.table },
        ),
      );
    }
  }
  const name = single && tables[0] ? tables[0].name : "schema";
  return {
    files: [{ path: `${name}.sql`, content: parts.join("\n"), language: "sql" }],
    warnings,
  };
}

function indexes(table: CodeTable, dialect: SqlDialect, warnings: CodeWarning[]): string[] {
  return table.indexes.map((index, n) => {
    let method = index.method;
    if (method && !dialect.indexMethods.has(method.toLowerCase())) {
      warnings.push(
        warn(
          "unsupported-index-method",
          { table: table.name, method, target: dialect.name },
          { table: table.name },
        ),
      );
      method = "";
    }
    const name = index.name || indexName(table.name, index.columns, index.unique, n);
    return dialect.index(table, { ...index, method }, name);
  });
}
